"use strict";
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const net = require("node:net");
const { spawn } = require("node:child_process");
const PNG = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1sAAAAASUVORK5CYII=";
test("HTTP upload → preview → existing skill run delivers image path; invalid references and cross-origin writes fail", async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "marketing-server-"));
  const app = path.join(temp, "app"), work = path.join(temp, "work");
  fs.cpSync(path.join(__dirname, "../app"), app, { recursive: true, filter: p => !/github-auth\.json|[\\/]materials$|[\\/]jobs$|config\.json|server\.pid/.test(p) });
  fs.mkdirSync(work); fs.writeFileSync(path.join(temp, "VERSION"), "0.0.0");
  const probe = net.createServer(); await new Promise(r => probe.listen(0, "127.0.0.1", r));
  const port = probe.address().port; await new Promise(r => probe.close(r));
  const fake = path.join(temp, "fake-claude"); fs.writeFileSync(fake, "test fixture");
  fs.writeFileSync(path.join(app, "config.json"), JSON.stringify({ port, projectDir: work, claudeExe: fake }));
  const child = spawn(process.execPath, ["--require", path.join(__dirname, "fixtures/fake-claude.cjs"), path.join(app, "server.js")], { env: { ...process.env, MSL_TEST_CLAUDE: fake }, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
  t.after(async () => { const ended = new Promise(r => child.once("close", r)); child.kill(); await ended; fs.rmSync(temp, { recursive: true, force: true }); });
  await new Promise((resolve, reject) => { const timeout = setTimeout(() => reject(new Error("server startup timed out")), 10000); child.stdout.on("data", d => { if (d.toString().includes("http://")) { clearTimeout(timeout); resolve(); } }); child.once("error", reject); });
  const base = `http://127.0.0.1:${port}`;
  const post = (url, data, headers = {}) => fetch(base + url, { method: "POST", headers: { "content-type": "application/json", "x-runner": "1", ...headers }, body: JSON.stringify(data) });
  let res = await post("/api/materials/images", { name: "통계.png", data: PNG }); assert.equal(res.status, 200);
  const image = await res.json();
  res = await fetch(base + `/api/materials/${image.id}/image`); assert.equal(res.headers.get("content-type"), "image/png");
  assert.equal(Buffer.from(await res.arrayBuffer()).toString("base64"), PNG);
  res = await post("/api/run", { skill: "seo-audit", prompt: "/seo-audit 테스트", materialIds: [image.id] }); assert.equal(res.status, 200);
  const job = await res.json(); assert.equal(job.materials[0].id, image.id);
  for (let i = 0; i < 30 && !fs.existsSync(path.join(work, "captured-prompt.txt")); i++) await new Promise(r => setTimeout(r, 30));
  const prompt = fs.readFileSync(path.join(work, "captured-prompt.txt"), "utf8");
  assert.ok(prompt.startsWith("/seo-audit 테스트")); assert.ok(prompt.includes(image.path));
  assert.equal((await post("/api/run", { skill: "seo-audit", prompt: "/seo-audit 테스트", materialIds: ["f".repeat(32)] })).status, 404);
  assert.equal((await post("/api/materials/images", { data: PNG }, { origin: "https://other.test" })).status, 403);
  assert.equal((await post("/api/materials/images", { data: "fake" })).status, 400);
  assert.equal((await post("/api/run", { skill: "seo-audit", prompt: "/seo-audit 기존 입력" })).status, 200);
});
